"""Fetch the M1 art: the 118 prototype birds in both styles.

Reads the bird list from prototype/animarka_prototype.html, downloads each bird
from the two source repos, trims transparent borders, writes WebP files under
web/public/art/{fg,wb}/ and generates web/src/catalog/static-m1.ts.

Run from the repo root:  python -I scripts/fetch_m1_art.py
Needs Pillow. Raw downloads are cached in data/m1-cache/ (ignored by git).
"""

from __future__ import annotations

import io
import json
import re
import sys
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PROTOTYPE = ROOT / "prototype" / "animarka_prototype.html"
CACHE = ROOT / "data" / "m1-cache"
OUT = ROOT / "web" / "public" / "art"
TS_OUT = ROOT / "web" / "src" / "catalog" / "static-m1.ts"

FG_BASE = "https://raw.githubusercontent.com/alchaincyf/huashu-bird-sticker/main"
WB_BASE = "https://raw.githubusercontent.com/adamoberley/HABirdDashboard/HABirdDashboard"
LONG_EDGE = 640
ALPHA_THRESHOLD = 8


def fetch(url: str, dest: Path) -> bool:
    if dest.exists() and dest.stat().st_size > 0:
        return True
    dest.parent.mkdir(parents=True, exist_ok=True)
    req = urllib.request.Request(url, headers={"User-Agent": "art-fetch-script"})
    try:
        with urllib.request.urlopen(req, timeout=120) as res:
            data = res.read()
    except (urllib.error.HTTPError, urllib.error.URLError, TimeoutError):
        return False
    dest.write_bytes(data)
    return True


def read_prototype() -> tuple[list[list], set[str], list[str]]:
    html = PROTOTYPE.read_text(encoding="utf-8")
    raw = json.loads(re.search(r"var RAW = (\[\[.*?\]\]);", html).group(1))
    flip = set(json.loads(re.search(r"var WB_FLIP = (\{.*?\});", html).group(1)))
    starter = json.loads(re.search(r"var STARTER = (\[.*?\])\.filter", html).group(1))
    return raw, flip, starter


def trim_and_save(src: Path, dest: Path) -> tuple[int, int]:
    im = Image.open(io.BytesIO(src.read_bytes())).convert("RGBA")
    mask = im.getchannel("A").point(lambda a: 255 if a > ALPHA_THRESHOLD else 0)
    box = mask.getbbox()
    if box:
        im = im.crop(box)
    im.thumbnail((LONG_EDGE, LONG_EDGE), Image.LANCZOS)
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest, "WEBP", quality=84, method=4)
    return im.size


def main() -> int:
    raw, flip, starter = read_prototype()
    print(f"prototype: {len(raw)} birds, {len(flip)} woodblock birds face right")

    species_json = CACHE / "species.json"
    if not fetch(f"{FG_BASE}/data/species.json", species_json):
        print("could not download species.json")
        return 1
    by_slug = {
        s["id"].lower().replace("_", "-"): s
        for s in json.loads(species_json.read_text(encoding="utf-8"))["species"]
    }

    jobs: list[tuple[str, str, str, Path]] = []
    missing: list[tuple[str, str, str]] = []
    for slug, *_ in raw:
        sp = by_slug.get(slug)
        if sp is None:
            missing.append((slug, "fg", "not in species.json"))
        else:
            tax = sp["taxonomy"]
            url = f"{FG_BASE}/stickers/{tax['order']}/{tax['family']}/{sp['id']}.webp"
            jobs.append((slug, "fg", url, CACHE / "fg" / f"{slug}.webp"))
        url = f"{WB_BASE}/avian/assets/illustrations/{slug}.png"
        jobs.append((slug, "wb", url, CACHE / "wb" / f"{slug}.png"))

    with ThreadPoolExecutor(max_workers=8) as pool:
        results = list(pool.map(lambda j: fetch(j[2], j[3]), jobs))

    sizes: dict[tuple[str, str], tuple[int, int]] = {}
    for (slug, style, url, path), ok in zip(jobs, results, strict=True):
        if not ok:
            missing.append((slug, style, url))
            continue
        sizes[(slug, style)] = trim_and_save(path, OUT / style / f"{slug}.webp")

    rows = []
    for slug, name, sci, family, mass in raw:
        if (slug, "fg") not in sizes or (slug, "wb") not in sizes:
            continue
        sp = by_slug.get(slug, {})
        tax = sp.get("taxonomy", {})
        fw, fh = sizes[(slug, "fg")]
        ww, wh = sizes[(slug, "wb")]
        rows.append(
            {
                "id": slug,
                "name": name,
                "sci": sci,
                "family": family,
                "order": tax.get("order", ""),
                "familySci": tax.get("family", ""),
                "massG": mass,
                "art": {
                    "fg": {"w": fw, "h": fh, "faces": "left"},
                    "wb": {"w": ww, "h": wh, "faces": "right" if slug in flip else "left"},
                },
            }
        )

    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    TS_OUT.write_text(
        "// Generated by scripts/fetch_m1_art.py. Do not edit by hand.\n"
        "// M1 static catalog: the 118 prototype birds. Replaced by the API in M2.\n\n"
        'export type Faces = "left" | "right" | "front";\n'
        "export type StaticArt = { w: number; h: number; faces: Faces };\n"
        "export type StaticSpecies = {\n"
        "  id: string;\n  name: string;\n  sci: string;\n  family: string;\n"
        "  order: string;\n  familySci: string;\n  massG: number;\n"
        "  art: { fg: StaticArt; wb: StaticArt };\n};\n\n"
        f"export const STARTER_IDS: string[] = {json.dumps(starter)};\n\n"
        f"export const SPECIES: StaticSpecies[] = [\n{body},\n];\n",
        encoding="utf-8",
        newline="\n",
    )

    total = sum(f.stat().st_size for f in OUT.rglob("*.webp"))
    print(f"wrote {len(sizes)} images, {total / 1e6:.1f} MB, {len(rows)} species in {TS_OUT.name}")
    if missing:
        print(f"missing {len(missing)}:")
        for m in missing:
            print("  ", *m)
    else:
        print("missing: none")
    return 0


if __name__ == "__main__":
    sys.exit(main())
